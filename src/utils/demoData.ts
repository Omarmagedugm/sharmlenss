// Helper to generate photo items for customers
export const generateDemoPhotos = (): Photo[] => {
  const photos: Photo[] = [];
  let photoIdx = 1;

  demoCustomers.forEach((cust) => {
    // Generate 6 photos for each customer
    for (let i = 0; i < 6; i++) {
      const imgUrl = sampleMarinePhotos[(photoIdx + i) % sampleMarinePhotos.length];
      const isSelected = i < 3;
      photos.push({
        id: `photo-${cust.id}-${i + 1}`,
        tripId: cust.tripId,
        customerId: cust.id,
        photographerId: cust.photographerId,
        url: imgUrl,
        previewUrl: imgUrl,
        caption: `Red Sea Excursion • Shot ${i + 1} for ${cust.fullName}`,
        status: isSelected ? 'selected' : 'preview',
        selectedByCustomer: isSelected,
        createdAt: cust.createdAt,
        updatedAt: cust.updatedAt,
      });
    }
    photoIdx++;
  });

  return photos;
};

